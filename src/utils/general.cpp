#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "../types.h"

uint32 uppow2(uint32 n)
{
	if (n == 0)
		return 0;

	// Spread the highest set bit downward, then add one to reach the next power
	// of two. If that power is 2^32, unsigned wraparound returns 0.
	--n;
	n |= n >> 1;
	n |= n >> 2;
	n |= n >> 4;
	n |= n >> 8;
	n |= n >> 16;
	return n + 1;
}

